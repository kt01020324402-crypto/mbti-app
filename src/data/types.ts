// 각 유형에 연결된 동물 캐릭터 정보입니다.
export interface MbtiCharacter {
  // 동물 종류 (예: 부엉이)
  animal: string;
  // 동물에 어울리는 캐릭터 이름 (예: 솔솔 부엉이)
  name: string;
}

// 1가지 MBTI 유형에 대한 전체 설명 데이터 구조입니다.
export interface MbtiTypeInfo {
  // 4글자 유형 코드
  code: MbtiTypeCode;
  // 유형의 특징을 담은 한글 별명
  nickname: string;
  // 짧은 한 줄 소개
  summary: string;
  // 성격 특징을 3~4문장으로 풀어낸 설명
  description: string;
  // 강점 3가지
  strengths: [string, string, string];
  // 조심하면 좋은 점 2가지
  cautions: [string, string];
  // 잘 어울리는 유형 코드 2가지
  compatibleTypes: [MbtiTypeCode, MbtiTypeCode];
  // 유형을 대표하는 파스텔 톤 HEX 색상
  color: string;
  // 3D 동물 캐릭터 정보
  character: MbtiCharacter;
}

